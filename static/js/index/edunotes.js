function addTableText(tableID, word, spanContent) {
    // Access table
    const tables = document.querySelectorAll(tableID);

    // Loop through to find the word
    tables.forEach(table => {

        const rows = table.rows;
        for (let i = 0; i < rows.length; i++) {
            // Access first cell of each row
            const firstCell = rows[i].cells[0];
            if (firstCell && firstCell.textContent.includes(word)) {

                firstCell.classList.add('CellWithComment');
                // Create span element
                const span = document.createElement('span');
                span.textContent = spanContent;
                span.classList.add('CellComment');

                firstCell.appendChild(span);
            }
        }
    });
}

